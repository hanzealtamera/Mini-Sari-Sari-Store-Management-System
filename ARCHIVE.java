private void loadUtangReports() {
    DefaultTableModel model =
            (DefaultTableModel) jTable1.getModel();

    model.setRowCount(0);

    String sql = "SELECT utang_id, customer_lastname, "
            + "customer_firstname, contact_number, item, "
            + "amount, amount_paid, due_date, status "
            + "FROM utang_report "
            + "ORDER BY utang_report_id DESC";

    try (Connection con = DBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql);
         ResultSet rs = pst.executeQuery()) {

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("utang_id"),
                rs.getString("customer_lastname"),
                rs.getString("customer_firstname"),
                rs.getString("contact_number"),
                rs.getString("item"),
                rs.getDouble("amount"),
                rs.getDouble("amount_paid"),
                rs.getDate("due_date"),
                rs.getString("status")
            });
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error loading utang archive: " + e.getMessage());
    }
}




