    private void addproductsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addproductsActionPerformed
        String name = JOptionPane.showInputDialog(
            this, "Enter Product Name:");

    if (name == null || name.trim().isEmpty()) return;

    String category = JOptionPane.showInputDialog(
            this, "Enter Category:");

    if (category == null || category.trim().isEmpty()) return;

    String priceText = JOptionPane.showInputDialog(
            this, "Enter Price:");

    if (priceText == null) return;

    String stockText = JOptionPane.showInputDialog(
            this, "Enter Stock:");

    if (stockText == null) return;

    try {
        double price = Double.parseDouble(priceText.trim());
        int stock = Integer.parseInt(stockText.trim());

        if (price < 0 || stock < 0) {
            JOptionPane.showMessageDialog(this,
                    "Price and stock cannot be negative.");
            return;
        }

        // Replace 1 with the actual logged-in owner's ID.
        int ownerId = 1;

        String sql = "INSERT INTO product "
                + "(owner_id, product_name, category, price, stock) "
                + "VALUES (?, ?, ?, ?, ?)";

        try (Connection con = DBConnection.getConnection()) {
            if (con == null) {
                JOptionPane.showMessageDialog(this,
                        "Database connection failed.");
                return;
            }

            try (PreparedStatement pst = con.prepareStatement(
                    sql, java.sql.Statement.RETURN_GENERATED_KEYS)) {

                pst.setInt(1, ownerId);
                pst.setString(2, name.trim());
                pst.setString(3, category.trim());
                pst.setDouble(4, price);
                pst.setInt(5, stock);

                pst.executeUpdate();

                try (ResultSet rs = pst.getGeneratedKeys()) {
                    if (rs.next()) {
                        productModel.addRow(new Object[]{
                            rs.getInt(1),
                            name.trim(),
                            category.trim(),
                            price,
                            stock
                        });
                    } else {
                        loadProducts();
                    }
                }
            }
        }

        JOptionPane.showMessageDialog(this,
                "Product added successfully!");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Enter a valid price and whole-number stock.");
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Could not add product: " + e.getMessage());
    }
    }//GEN-LAST:event_addproductsActionPerformed

