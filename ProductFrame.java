    private void EDITActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EDITActionPerformed
        int row = products.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Please select a product first.");
        return;
    }

    int id = Integer.parseInt(products.getValueAt(row, 0).toString());
    String name = products.getValueAt(row, 1).toString();
    String category = products.getValueAt(row, 2).toString();
    String price = products.getValueAt(row, 3).toString();
    String stock = products.getValueAt(row, 4).toString();

    String[] choices = {"Product Name", "Category", "Price", "Stock", "Cancel"};

    String choice = (String) JOptionPane.showInputDialog(
        this,
        "Product: " + name + "\nChoose what to edit:",
        "Edit Product",
        JOptionPane.QUESTION_MESSAGE,
        null,
        choices,
        choices[0]
    );

    if (choice == null || choice.equals("Cancel")) {
        return;
    }

    String column = "";
    Object newValue;

    try {
        if (choice.equals("Product Name")) {
            String value = JOptionPane.showInputDialog(this, "Enter new product name:", name);
            if (value == null || value.trim().isEmpty()) return;
            column = "product_name";
            newValue = value.trim();

        } else if (choice.equals("Category")) {
            String value = JOptionPane.showInputDialog(this, "Enter new category:", category);
            if (value == null || value.trim().isEmpty()) return;
            column = "category";
            newValue = value.trim();

        } else if (choice.equals("Price")) {
            String value = JOptionPane.showInputDialog(this, "Enter new price:", price);
            if (value == null) return;

            double number = Double.parseDouble(value.trim());
            if (number < 0) {
                JOptionPane.showMessageDialog(this, "Price cannot be negative.");
                return;
            }

            column = "price";
            newValue = number;

        } else {
            String value = JOptionPane.showInputDialog(this, "Enter new stock:", stock);
            if (value == null) return;

            int number = Integer.parseInt(value.trim());
            if (number < 0) {
                JOptionPane.showMessageDialog(this, "Stock cannot be negative.");
                return;
            }

            column = "stock";
            newValue = number;
        }

        updateProduct(id, column, newValue);

        if (column.equals("product_name")) {
            products.setValueAt(newValue, row, 1);
        } else if (column.equals("category")) {
            products.setValueAt(newValue, row, 2);
        } else if (column.equals("price")) {
            products.setValueAt(newValue, row, 3);
        } else if (column.equals("stock")) {
            products.setValueAt(newValue, row, 4);
        }

        JOptionPane.showMessageDialog(this, "Product updated successfully!");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Enter a valid number for price or stock.");
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this, "Database update failed: " + e.getMessage());
    }
    }//GEN-LAST:event_EDITActionPerformed
    private void updateProduct(int id, String column, Object value)
        throws java.sql.SQLException {

    String sql = "UPDATE product SET " + column
               + " = ? WHERE product_id = ?";

    try (Connection con = DBConnection.getConnection()) {
        if (con == null) {
            throw new java.sql.SQLException(
                    "Database connection failed.");
        }

        try (PreparedStatement pst = con.prepareStatement(sql)) {
            pst.setObject(1, value);
            pst.setInt(2, id);

            if (pst.executeUpdate() == 0) {
                throw new java.sql.SQLException(
                        "Product was not found in the database.");
            }
        }
    }
}
