    private void searchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchActionPerformed
 String searchText = PROsearch.getText().trim().toLowerCase();

    if (searchText.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Enter a product name.");
        return;
    }

    for (int i = 0; i < productModel.getRowCount(); i++) {
        Object value = productModel.getValueAt(i, 1);

        if (value != null &&
                value.toString().toLowerCase().contains(searchText)) {
            products.setRowSelectionInterval(i, i);
            products.scrollRectToVisible(
                    products.getCellRect(i, 0, true));
            return;
        }
    }

    JOptionPane.showMessageDialog(this, "Product not found.");
    }//GEN-LAST:event_searchActionPerformed

